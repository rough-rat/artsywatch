use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // generated from the ledface PCB: ledface_layout/tools/gen_great_voltage_wave.py
    let json_path = manifest_dir.join("ledface_layout/great_voltage_wave.json");

    println!("cargo:rerun-if-changed={}", json_path.display());

    // linker check: at least 4 KB of RAM left for the stack, see stack-check.x
    println!("cargo:rustc-link-search={}", manifest_dir.display());
    println!("cargo:rustc-link-arg-bins=-Tstack-check.x");
    println!("cargo:rerun-if-changed=stack-check.x");

    let data = fs::read(&json_path).expect("failed to read layout JSON");
    let layout: ledface_layout::Layout<64, 16, 64> =
        ledface_layout::Layout::from_json(&data).expect("invalid layout JSON");

    // Emit what the clock needs as Rust constants (OUT_DIR/face.rs), so the firmware doesn't
    // decode the layout at run time: that took a 9.3 KB stack frame on a ~10 KB stack.
    const LEDS: usize = 48;
    let (mut x, mut y) = ([0i32; LEDS], [0i32; LEDS]);
    for led in layout.leds.iter() {
        let i = led.index as usize;
        assert!(i < LEDS, "LED index {} out of range", i);
        x[i] = (led.x_mm * 10.0).round() as i32;
        y[i] = (led.y_mm * 10.0).round() as i32;
    }
    let map = |name: &str| -> Vec<u8> {
        let entity = layout.entity(name).unwrap_or_else(|| panic!("layout: entity {} missing", name));
        entity.map.iter().map(|&i| {
            assert!((i as usize) < LEDS, "entity {}: LED index {} out of range", name, i);
            i as u8
        }).collect()
    };
    let (minutes, hours, wave) = (map("Minutes"), map("Hours"), map("Wave"));
    assert!(minutes.len() >= 6 && hours.len() >= 5 && !wave.is_empty(), "layout: entities too small");
    let xs = wave.iter().map(|&i| x[i as usize]);
    let ys = wave.iter().map(|&i| y[i as usize]);
    let face = format!(
        "// generated by build.rs from {json}\n\
         static FACE: Face = Face {{\n\
         \x20   minutes: &{minutes:?},\n\
         \x20   hours: &{hours:?},\n\
         \x20   wave: &{wave:?},\n\
         \x20   x: {x:?},\n\
         \x20   y: {y:?},\n\
         \x20   wave_left: {l},\n\
         \x20   wave_right: {r},\n\
         \x20   wave_top: {t},\n\
         \x20   wave_bottom: {b},\n\
         }};\n",
        json = json_path.file_name().unwrap().to_string_lossy(),
        l = xs.clone().min().unwrap(),
        r = xs.max().unwrap(),
        t = ys.clone().min().unwrap(),
        b = ys.max().unwrap(),
    );
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("face.rs"), face).expect("failed to write face.rs");
}
