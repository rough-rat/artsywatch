#!/usr/bin/env python3
"""Generate the Great Voltage Wave ledface layout JSON from its KiCad PCB.

LED -> firmware index: the drivers are chained U101 -> U102 -> U103 (DAT into U101), and
ch58x-rs-kit's pack_bits() puts index 16 * chip + output on (chip 0 = U103, 1 = U102,
2 = U101). Positions are the LED footprint centres, relative to the top-left LED, in mm.

    tools/gen_great_voltage_wave.py > great_voltage_wave.json
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PCB = ROOT / "hardware/great_voltage_wave_ledface/great_voltage_wave_ledface.kicad_pcb"

# LED Dn cathode -> (driver, output), from the schematic
CHIP = {"U103": 0, "U102": 1, "U101": 2}
def driver_output(n):
    if 3 <= n <= 18:
        return "U103", 18 - n
    if 19 <= n <= 34:
        return "U102", n - 19
    return "U101", n - 35

def main():
    text = PCB.read_text()
    pos = {}
    for m in re.finditer(r'\(footprint "([^"]*)"(.*?)\n\t\)', text, re.S):
        body = m.group(2)
        ref = re.search(r'\(property "Reference" "(D\d+)"', body)
        at = re.search(r'\n\t\t\(at ([-\d.]+) ([-\d.]+)', body)
        if ref and at:
            pos[int(ref.group(1)[1:])] = (float(at.group(1)), float(at.group(2)))

    leds = []
    for n in range(3, 51):
        chip, out = driver_output(n)
        leds.append((16 * CHIP[chip] + out, n, *pos[n]))
    x0 = min(l[2] for l in leds)
    y0 = min(l[3] for l in leds)

    def index_of(n):
        return next(l[0] for l in leds if l[1] == n)

    # kanji columns, read right to left, each top to bottom
    text_leds = [l for l in leds if 3 <= l[1] <= 15]
    columns = sorted({l[2] for l in text_leds}, reverse=True)
    reading = [l for x in columns for l in sorted((l for l in text_leds if l[2] == x), key=lambda l: l[3])]
    minutes = [l[0] for l in reading[:7]]
    hours = [l[0] for l in reading[7:]]
    wave = [l[0] for l in sorted((l for l in leds if l[1] not in range(3, 16)), key=lambda l: (l[2], l[3]))]

    layout = {
        "watchface": {"name": "Great Voltage Wave", "version": 1,
                      "notes": "generated by tools/gen_great_voltage_wave.py"},
        "leds": [{"index": i, "name": f"D{n}", "x_mm": round(x - x0, 3), "y_mm": round(y - y0, 3)}
                 for i, n, x, y in sorted(leds)],
        "entities": [
            {"name": "Minutes", "type": "group", "map": minutes},
            {"name": "Hours", "type": "group", "map": hours},
            {"name": "Wave", "type": "group", "map": wave},
        ],
    }
    json.dump(layout, sys.stdout, indent=2)
    print()

if __name__ == "__main__":
    main()
